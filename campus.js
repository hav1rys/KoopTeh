/** Этаж по номеру кабинета (число или строка), либо null. */
function floorOf(room) {
  const key = String(room || '').trim().toLowerCase().replace(/\s+/g, '');
  if (FLOORS[key] != null) return FLOORS[key];
  const n = parseInt(key, 10);
  return Number.isFinite(n) && FLOORS[n] != null ? FLOORS[n] : null;
}

